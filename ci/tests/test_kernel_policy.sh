# ci/tests/test_kernel_policy.sh — kernel-policy 门禁回归夹具
#
# 门禁除内核树外还要读契约源、生成器、生成物、TAP 基线与流水线文件，这些
# 路径都按仓库根解析。夹具因此把门禁与它的库复制进一棵临时仓库，在假
# 树里逐组破坏：契约版本、运行期字段、生成物一致性、注册顺序、基线用例、
# 流水线接线。断言只看退出码与稳定判据字符串。
#
# 用法: bash ci/tests/test_kernel_policy.sh
# 退出码: 0 全部断言通过；1 有断言失败。
# ===========================================================================
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT
BASE="${tmp}/base"
fails=0

ok() { printf 'ok   %s\n' "$*"; }
bad() { printf 'FAIL %s\n' "$*"; fails=$((fails + 1)); }

run() { GITHUB_ACTIONS='' bash "${BASE}/ci/gates/kernel-policy.sh" "$@" 2>&1; }

check()
{
    local name="$1" want="$2" got="$3" out="$4" needle="$5"

    if [ "${got}" != "${want}" ]; then
        bad "${name}（rc=${got}，期望 ${want}）"
        printf '%s\n' "${out}" >&2
        return 0
    fi
    case "${out}" in
    *"${needle}"*) ok "${name}" ;;
    *) bad "${name}（输出缺「${needle}」）"; printf '%s\n' "${out}" >&2 ;;
    esac
}

# hdr FILE — 两份生成物共用的形态（示例侧与内核侧逐字节一致）
hdr()
{
    {
        printf '/* SPDX-License-Identifier: GPL-2.0-only */\n'
        printf '/* Copyright (C) 2025-2026 SPHARX Ltd. */\n'
        printf '/* DO NOT EDIT: generated by tools/dsl/dsl_compile.py */\n'
        printf 'static const struct airy_policy_table airy_policy_uring_guard_table = {\n'
        printf '        { .verdict = 1, .fault = 0x100A },\n};\n'
        printf 'static const struct airy_policy_table airy_policy_task_guard_table = {\n'
        printf '        { .verdict = 0, .fault = 0 },\n};\n'
        printf 'static const struct airy_policy_table airy_policy_file_open_guard_table = {\n'
        printf '        { .verdict = 0, .fault = 0 },\n};\n'
    } >"$1"
}

# adl FILE — 契约源：三张表、六个运行期字段
adl()
{
    {
        printf 'version "1.0.1";\n'
        printf 'table uring_guard {\n  hook = uring_cmd;\n'
        printf '  input op : u32;\n  input cmd_flags : u32;\n}\n'
        printf 'table task_guard {\n  hook = task_alloc;\n'
        printf '  input clone_flags : u64;\n  input task_type : u32;\n}\n'
        printf 'table file_open_guard {\n  hook = file_open;\n'
        printf '  input acc_mode : u32;\n  input open_flags : u32;\n}\n'
    } >"$1"
}

mkdir -p "${BASE}/ci/gates" "${BASE}/ci/lib" "${BASE}/tools/dsl/examples" \
    "${BASE}/tools/tap" "${BASE}/.github/workflows" \
    "${BASE}/kernel/security/airy" "${BASE}/kernel/include/airymax"
cp "${ROOT}/ci/gates/kernel-policy.sh" "${BASE}/ci/gates/"
cp "${ROOT}/ci/lib/log.sh" "${ROOT}/ci/lib/opts.sh" "${BASE}/ci/lib/"
ORIG_ADL="${BASE}/tools/dsl/examples/security_policy.adl"
adl "${ORIG_ADL}"

cat >"${BASE}/tools/dsl/dsl_compile.py" <<'EOF'
# SPDX-License-Identifier: Apache-2.0
OUT = Path("kernel") / "security" / "airy" / "security_policy_tables.h"
EOF
hdr "${BASE}/tools/dsl/examples/security_policy_tables.h"
hdr "${BASE}/kernel/security/airy/security_policy_tables.h"
{
    printf '// SPDX-License-Identifier: GPL-2.0-only\n'
    printf '// Copyright (C) 2025-2026 SPHARX Ltd.\n'
    printf '#include "security_policy_tables.h"\n'
    printf 'static const void *airy_policy_tables[] = {\n'
    printf '        airy_policy_uring_guard_table,\n'
    printf '        airy_policy_task_guard_table,\n'
    printf '        airy_policy_file_open_guard_table,\n};\n'
    printf 'static int reg(int i) { return airy_policy_register(airy_policy_tables[i]); }\n'
} >"${BASE}/kernel/security/airy/airy_policy_tables.c"
printf '// SPDX-License-Identifier: GPL-2.0-only\n' \
    >"${BASE}/kernel/security/airy/airy_policy.c"
for f in op cmd_flags clone_flags task_type acc_mode open_flags; do
    printf '        "%s",\n' "${f}" >>"${BASE}/kernel/security/airy/airy_policy.c"
done
{
    printf '// SPDX-License-Identifier: GPL-2.0-only\n'
    printf '// Copyright (C) 2025-2026 SPHARX Ltd.\n'
    printf 'static int airy_init(void)\n{\n'
    printf '        airy_policy_register(&airy_wx_table);\n'
    printf '        return airy_policy_tables_register();\n}\n'
} >"${BASE}/kernel/security/airy/airy_lsm.c"
printf 'int airy_policy_tables_register(void);\n' \
    >"${BASE}/kernel/include/airymax/airy_policy.h"
{
    printf '// SPDX-License-Identifier: GPL-2.0-only\n'
    printf 'KUNIT_CASE(policy_tables);\n'
    printf 'static void run(void) { airy_policy_tables_register(); }\n'
} >"${BASE}/kernel/security/airy/airy_policy_test.c"
printf 'airy_policy-y := airy_policy.o airy_policy_tables.o\n' \
    >"${BASE}/kernel/security/airy/Kbuild"
printf '    ok 1 policy_tables\n' >"${BASE}/tools/tap/kunit-tap-baseline.tap"
printf 'steps:\n  - run: ci/ci.sh kernel-policy\n' \
    >"${BASE}/.github/workflows/kernel-verify.yml"

# mutate NAME [REL SED-EXPR...] — 复制合规树，按成对参数各改一处
mutate()
{
    local name="$1" tree="${tmp}/$1"

    shift
    cp -a "${BASE}" "${tree}"
    while [ "$#" -ge 2 ]; do
        sed -i "$2" "${tree}/$1"
        shift 2
    done
    printf '%s\n' "${tree}"
}

# runin TREE [ARGS...] — 在指定树里跑门禁
runin()
{
    local tree="$1"

    shift
    GITHUB_ACTIONS='' bash "${tree}/ci/gates/kernel-policy.sh" "$@" 2>&1
}

out="$(run -h)"; rc=$?
check "帮助退 0" 0 "${rc}" "${out}" "用法:"

out="$(run)"; rc=$?
check "合规树通过" 0 "${rc}" "${out}" "决策表契约门禁通过"

# 负向：契约源
t="$(mutate bad-version tools/dsl/examples/security_policy.adl \
    's/^version "1.0.1";/version "1.0.0";/')"
out="$(runin "${t}")"; rc=$?
check "契约版本漂移" 1 "${rc}" "${out}" "契约版本不是 1.0.1"

t="$(mutate no-field tools/dsl/examples/security_policy.adl \
    '/input cmd_flags/d')"
out="$(runin "${t}")"; rc=$?
check "契约源缺运行期字段" 1 "${rc}" "${out}" "缺少运行期字段 cmd_flags"

t="$(mutate dead-field tools/dsl/examples/security_policy.adl \
    's/^  input open_flags : u32;/&\n  input cap_flags : u32;/')"
out="$(runin "${t}")"; rc=$?
check "契约源引用运行期不存在的字段" 1 "${rc}" "${out}" \
    "契约源仍引用运行期不存在的字段"

# 负向：生成物
t="$(mutate drift tools/dsl/examples/security_policy_tables.h \
    's/\.fault = 0x100A/.fault = 0x100B/')"
out="$(runin "${t}")"; rc=$?
check "示例与内核侧生成物不一致" 1 "${rc}" "${out}" \
    "示例与内核侧生成物不一致"

t="$(mutate deny-watch kernel/security/airy/security_policy_tables.h \
    's/\.verdict = 0, \.fault = 0 }/.verdict = 1, .fault = 0 }/')"
out="$(runin "${t}")"; rc=$?
check "观测基线出现 DENY 行" 1 "${rc}" "${out}" \
    "观测表出现 DENY 行"

# 负向：启动顺序（两处调用互换位置，而不是删掉其中一处）
reorder_tree()
{
    local tree="${tmp}/bad-order"

    cp -a "${BASE}" "${tree}"
    cat >"${tree}/kernel/security/airy/airy_lsm.c" <<'EOF'
// SPDX-License-Identifier: GPL-2.0-only
// Copyright (C) 2025-2026 SPHARX Ltd.
static int airy_init(void)
{
        airy_policy_tables_register();
        return airy_policy_register(&airy_wx_table);
}
EOF
    printf '%s\n' "${tree}"
}

t="$(reorder_tree)"
out="$(runin "${t}")"; rc=$?
check "参考策略先于 W^X 表注册" 1 "${rc}" "${out}" \
    "参考策略必须在 W^X 表之后注册"

# 负向：测试基线
t="$(mutate no-tap tools/tap/kunit-tap-baseline.tap '/policy_tables/d')"
out="$(runin "${t}")"; rc=$?
check "TAP 基线缺 policy_tables" 1 "${rc}" "${out}" \
    "TAP 基线缺少 policy_tables"

# 负向：流水线接线与契约文件缺席
t="$(mutate no-hook .github/workflows/kernel-verify.yml \
    's#ci/ci.sh kernel-policy#true#')"
out="$(runin "${t}")"; rc=$?
check "流水线未调用门禁" 1 "${rc}" "${out}" \
    "kernel-verify.yml 未调用 kernel-policy 门禁"

t="${tmp}/no-contract"
cp -a "${BASE}" "${t}"
rm -f "${t}/tools/tap/kunit-tap-baseline.tap"
out="$(runin "${t}")"; rc=$?
check "契约文件缺席退 5" 5 "${rc}" "${out}" "契约文件"

if [ "${fails}" -ne 0 ]; then
    printf 'test_kernel_policy: %d 项失败\n' "${fails}" >&2
    exit 1
fi
printf 'test_kernel_policy: 全部通过\n'
